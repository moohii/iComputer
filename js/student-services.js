document.addEventListener("DOMContentLoaded", () => {
  const rows = [...document.querySelectorAll("#trainingCentreRows tr")];
  const municipalityFilter = document.getElementById("municipalityFilter");
  const typeFilter = document.getElementById("institutionTypeFilter");
  const resultCount = document.getElementById("directoryResultCount");
  const emptyState = document.getElementById("directoryEmptyState");
  const form = document.getElementById("studentQuoteForm");
  const status = document.getElementById("quoteFormStatus");
  const whatsappLink = document.getElementById("studentWhatsappLink");
  let currentLanguage = "fr";

  function getDictionary() {
    return studentServiceTranslations[currentLanguage];
  }

  function applyDirectoryFilters() {
    const municipality = municipalityFilter.value;
    const type = typeFilter.value;
    let visibleCount = 0;

    rows.forEach(row => {
      const visible = (municipality === "all" || row.dataset.municipality === municipality)
        && (type === "all" || row.dataset.type === type);
      row.hidden = !visible;
      if (visible) visibleCount++;
    });

    resultCount.textContent = `${visibleCount} ${getDictionary()["directory.results"]}`;
    emptyState.hidden = visibleCount > 0;
  }

  function clearPreparedMessage() {
    whatsappLink.hidden = true;
    status.hidden = true;
    whatsappLink.href = "https://wa.me/rai.med.elamine";
  }

  function setStudentLanguage(language) {
    const dictionary = studentServiceTranslations[language];
    if (!dictionary) return;

    currentLanguage = language;
    document.documentElement.lang = language;
    document.documentElement.dir = language === "ar" ? "rtl" : "ltr";
    document.querySelectorAll("[data-student-i18n]").forEach(element => {
      const translation = dictionary[element.dataset.studentI18n];
      if (translation) element.textContent = translation;
    });
    document.querySelectorAll("[data-student-i18n-placeholder]").forEach(element => {
      const translation = dictionary[element.dataset.studentI18nPlaceholder];
      if (translation) element.placeholder = translation;
    });
    document.querySelectorAll(".lang-switch button").forEach(button => {
      button.classList.toggle("active", button.dataset.lang === language);
    });

    document.title = dictionary.title;
    document.querySelector('meta[name="description"]').content = dictionary.description;
    document.querySelector('meta[property="og:title"]').content = dictionary.ogTitle;
    document.querySelector('meta[property="og:description"]').content = dictionary.ogDescription;
    clearPreparedMessage();
    applyDirectoryFilters();
  }

  document.querySelectorAll(".lang-switch button").forEach(button => {
    button.addEventListener("click", () => setStudentLanguage(button.dataset.lang));
  });

  municipalityFilter.addEventListener("change", applyDirectoryFilters);
  typeFilter.addEventListener("change", applyDirectoryFilters);

  form.addEventListener("submit", event => {
    event.preventDefault();

    if (!form.reportValidity()) return;

    const dictionary = getDictionary();
    const documentType = form.elements.documentType;
    const selectedServices = [...form.querySelectorAll('input[name="services"]:checked')]
      .map(input => dictionary[`form.service${input.value[0].toUpperCase()}${input.value.slice(1)}`]);
    const pageCount = form.elements.pageCount.value.trim();
    const deadline = form.elements.deadline.value.trim();
    const institutionLevel = form.elements.institutionLevel.value.trim();
    const lines = [
      dictionary["form.greeting"],
      `${dictionary["form.document"]}: ${documentType.selectedOptions[0].textContent}`,
      `${dictionary["form.pages"]}: ${pageCount || "-"}`,
      `${dictionary["form.services"]}: ${selectedServices.length ? selectedServices.join(", ") : dictionary["form.noServices"]}`,
      `${dictionary["form.deadline"]}: ${deadline || "-"}`,
      `${dictionary["form.level"]}: ${institutionLevel || "-"}`
    ];

    whatsappLink.href = `https://wa.me/rai.med.elamine?text=${encodeURIComponent(lines.join("\n"))}`;
    status.textContent = dictionary["form.status"];
    status.hidden = false;
    whatsappLink.hidden = false;
  });

  applyDirectoryFilters();
  let savedLanguage = "fr";
  try {
    savedLanguage = localStorage.getItem("lang") || "fr";
  } catch (error) {
    savedLanguage = "fr";
  }
  setStudentLanguage(savedLanguage);
});
